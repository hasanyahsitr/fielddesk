'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {translateUI}=require('../app/static/i18n.js');
assert.equal(translateUI('Genel bakış'),'Overview');
assert.equal(translateUI('Genel bakış','tr'),'Genel bakış');
assert.equal(translateUI('  Asistan\n'),'  Assistant\n');
assert.equal(translateUI('24 öğe · filtrelenmiş'),'24 items · filtered');
assert.equal(translateUI('1 program seçildi · Katalog: 30'),'1 program selected · Catalog: 30');
assert.equal(translateUI('Favorilere ekle: Notepad++'),'Add to favorites: Notepad++');
assert.equal(translateUI('Notepad++: aç'),'Notepad++: open');
assert.equal(translateUI('HandBrake seç'),'Select HandBrake');
assert.equal(translateUI('Geri alınabilir kaldırılanlar (2)'),'Removed apps · undo available (2)');
assert.equal(translateUI('Geri alınabilir kaldırılanlar (2)','tr'),'Geri alınabilir kaldırılanlar (2)');
assert.equal(translateUI('D:\\ATOLYE\\04_PROJELER'),'D:\\ATOLYE\\04_PROJELER');
assert.equal(translateUI('A user-authored sentence.'),'A user-authored sentence.');
assert.equal(translateUI('1 sayfa'),'1 page');
assert.equal(translateUI('Girdiler kontrol ediliyor. (0/2)'),'Checking inputs. (0/2)');
assert.equal(translateUI('Girdiler kontrol ediliyor. (0/2)','tr'),'Girdiler kontrol ediliyor. (0/2)');
assert.equal(translateUI('2 sayfa'),'2 pages');
assert.equal(translateUI('1 PDF → 1 sayfalı tek PDF'),'1 PDF → one PDF with 1 page');
assert.equal(translateUI('2 PDF → 3 sayfalı tek PDF'),'2 PDFs → one PDF with 3 pages');
assert.equal(translateUI('108 KB · 1 sayfa'),'108 KB · 1 page');
assert.equal(translateUI('1,024 KB · 2 sayfa'),'1,024 KB · 2 pages');
assert.equal(translateUI('Sıra aşağıdaki dosya sırasıdır. Yer işaretleri ve etkileşimli formlar korunmayabilir.'),'Files are processed in the order below. Bookmarks and interactive forms may not be preserved.');
assert.equal(translateUI('0 sonuç bulundu.'),'No results found.');
assert.equal(translateUI('1 sonuç bulundu.'),'1 result found.');
assert.equal(translateUI('2 sonuç bulundu.'),'2 results found.');
assert.equal(translateUI('Arama tamamlanamadı. Yeniden dene.'),'Search could not be completed. Try again.');
for(const value of ['2 PDF → 3 sayfalı tek PDF','108 KB · 1 sayfa','0 sonuç bulundu.','Arama tamamlanamadı. Yeniden dene.'])assert.equal(translateUI(value,'tr'),value);
assert.equal(translateUI('Model boş yanıt döndürdü. Yeniden dene veya başka bir model seç.'),'The model returned an empty response. Retry or choose another model.');
const html=fs.readFileSync(path.join(__dirname,'../app/static/index.html'),'utf8');
assert(html.indexOf('/i18n.js')<html.indexOf('/app.js'));
assert(html.indexOf('id="chat-mode-title"')<html.indexOf('id="chat-thread"'));
assert(html.includes('id="language-select"'));
assert(html.includes('data-user-content'));
