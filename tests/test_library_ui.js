'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const source=fs.readFileSync(path.join(__dirname,'../app/static/app.js'),'utf8');
const searchSource=source.slice(source.indexOf('let librarySearchSequence='),source.indexOf("document.addEventListener('click'"));
const html=fs.readFileSync(path.join(__dirname,'../app/static/index.html'),'utf8');
assert.match(html,/<p id="library-search-status"[^>]*role="status"[^>]*aria-live="polite"[^>]*aria-atomic="true"/);
assert.match(html,/<div id="library-results">/); // Do not announce entire excerpts.
const nodes={'#library-query':{value:'handover'},'#library-search-status':{},'#library-results':{}};
const requests=[];
const context=vm.createContext({$:(selector)=>nodes[selector],esc:(s)=>String(s).replace(/</g,'&lt;'),api:(url)=>new Promise((resolve,reject)=>requests.push({url,resolve,reject}))});
vm.runInContext(searchSource,context);
const search=()=>vm.runInContext('searchLibrary()',context);
const row={title:'Genel bakış',path:'04_PROJELER/Genel bakış.txt',excerpt:'<sample> private test text'};
(async()=>{
  let task=search();
  assert.equal(nodes['#library-search-status'].textContent,'Yerel dosyalarda aranıyor…');
  requests.shift().resolve({results:[row]});await task;
  assert.equal(nodes['#library-search-status'].textContent,'1 sonuç bulundu.');
  assert.match(nodes['#library-results'].innerHTML,/Genel bakış/);
  assert.match(nodes['#library-results'].innerHTML,/&lt;sample>/);
  assert(!nodes['#library-search-status'].textContent.includes('private test text'));
  nodes['#library-query'].value='çanta & PDF';task=search();
  const encoded=requests.shift();assert.equal(encoded.url,'/api/library/search?q='+encodeURIComponent('çanta & PDF'));
  encoded.resolve({results:[]});await task;
  assert.equal(nodes['#library-search-status'].textContent,'0 sonuç bulundu.');
  task=search();requests.shift().resolve({results:[row,row]});await task;
  assert.equal(nodes['#library-search-status'].textContent,'2 sonuç bulundu.');
  const older=search(),oldRequest=requests.shift(),newer=search(),newRequest=requests.shift();
  newRequest.resolve({results:[row]});await newer;
  oldRequest.resolve({results:[]});await older;
  assert.equal(nodes['#library-search-status'].textContent,'1 sonuç bulundu.');
  const failingOlder=search(),failure=requests.shift(),latest=search(),latestRequest=requests.shift();
  latestRequest.resolve({results:[]});await latest;
  failure.reject(Error('stale request'));await failingOlder;
  assert.equal(nodes['#library-search-status'].textContent,'0 sonuç bulundu.');
  task=search();requests.shift().reject(Error('offline'));
  await assert.rejects(task,/offline/);
  assert.equal(nodes['#library-search-status'].textContent,'Arama tamamlanamadı. Yeniden dene.');
  assert(!nodes['#library-results'].innerHTML.includes('Genel bakış'));
  const before=requests.length;nodes['#library-query'].value='  ';await search();assert.equal(requests.length,before);
  console.log('Library UI: loading, one/many/zero results, stale success/error, active failure and blank query passed');
})().catch(error=>{console.error(error);process.exitCode=1;});
